from __future__ import annotations

from enum import Enum
from typing import Any

from pydantic import BaseModel, Field


class DecisionStatus(str, Enum):
    """Enumeration of possible gating decision outcomes.

    Attributes:
        PASSED: Artifact satisfied all requirements and thresholds.
        FAILED: Artifact decisively failed verification.
        AMBIGUOUS: Confidence fell within the uncertainty band between fail and pass thresholds.
    """

    PASSED = "passed"
    FAILED = "failed"
    AMBIGUOUS = "ambiguous"


class LayerTrace(BaseModel):
    """Detailed execution telemetry and diagnostic trace for a single gate layer.

    Attributes:
        layer_name: Identifier of the executing gate layer (e.g., 'ASTGate', 'LogitGate').
        status: Decision status reached by this layer.
        latency_ms: Execution duration for this layer in milliseconds.
        calibrated_prob: Post-debiasing / calibrated probability (if applicable).
        forward_prob: Pass probability from forward permutation pass (Pass 1).
        reverse_prob: Pass probability from reverse permutation pass (Pass 2).
        forward_log_odds: Raw logit difference from forward pass (Pass 1).
        reverse_log_odds: Raw logit difference from reverse pass (Pass 2).
        tokens_generated: Count of autoregressive tokens generated by this layer.
        diagnostic_report: Text critique or diagnostic error message (if any).
        metadata: Arbitrary supplemental telemetry and token distributions.
    """

    layer_name: str
    status: DecisionStatus
    latency_ms: float
    calibrated_prob: float | None = None
    forward_prob: float | None = None
    reverse_prob: float | None = None
    forward_log_odds: float | None = None
    reverse_log_odds: float | None = None
    tokens_generated: int = 0
    diagnostic_report: str | None = None
    metadata: dict[str, Any] = Field(default_factory=dict)

    def __repr__(self) -> str:
        parts = [
            f"layer='{self.layer_name}'",
            f"status={self.status.value}",
            f"latency={self.latency_ms:.2f}ms",
        ]
        if self.calibrated_prob is not None:
            parts.append(f"prob={self.calibrated_prob:.4f}")
        if self.tokens_generated > 0:
            parts.append(f"tokens={self.tokens_generated}")
        return f"LayerTrace({', '.join(parts)})"


class Verdict(BaseModel):
    """Final aggregated evaluation outcome across single gates or cascaded pipelines.

    Attributes:
        passed: Boolean flag indicating if the candidate passed evaluation.
        status: Discrete decision status (PASSED, FAILED, AMBIGUOUS).
        probability: Debiased confidence score in [0.0, 1.0] (for binary/logit gates).
        score: Continuous expected score (for ScoreGate or scored judges).
        choice: Selected discrete option identifier (for ChoiceGate).
        choice_probabilities: Softmax probability distribution over discrete options.
        triggered_layer: Name of the gate layer that produced the terminating decision.
        total_latency_ms: Total cumulative evaluation latency in milliseconds.
        total_tokens_generated: Total cumulative autoregressive tokens generated.
        reason: Diagnostic summary, critique, or failure justification.
        traces: Ordered sequence of telemetry traces from each executed layer.
    """

    passed: bool
    status: DecisionStatus
    probability: float | None = None
    score: float | None = None
    choice: str | None = None
    choice_probabilities: dict[str, float] | None = None
    triggered_layer: str
    total_latency_ms: float
    total_tokens_generated: int = 0
    reason: str | None = None
    traces: list[LayerTrace] = Field(default_factory=list)

    def __bool__(self) -> bool:
        """Allows direct truthiness checks: `if verdict: ...`."""
        return self.passed

    def __repr__(self) -> str:
        parts = [f"status='{self.status.value}'"]
        if self.probability is not None:
            parts.append(f"prob={self.probability:.4f}")
        if self.score is not None:
            parts.append(f"score={self.score:.2f}")
        if self.choice is not None:
            parts.append(f"choice='{self.choice}'")
        parts.append(f"layer='{self.triggered_layer}'")
        parts.append(f"latency={self.total_latency_ms:.2f}ms")
        parts.append(f"tokens={self.total_tokens_generated}")
        return f"Verdict({', '.join(parts)})"
